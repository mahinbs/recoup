// Generates supabase/migrations/002_seed.sql from the data already in the site code.
// Run: node scripts/gen-seed.mjs
import { execSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const tmp = mkdtempSync(join(tmpdir(), 'seed-'));
const bundle = (entry, out) => execSync(`npx esbuild ${entry} --bundle --format=esm --loader:.json=json --loader:.jpg=dataurl --loader:.png=dataurl --outfile=${out} --log-level=error`, { stdio: 'inherit' });
bundle('src/conditions/conditions.js', join(tmp, 'cond.mjs'));
bundle('src/data/defaultBlogPosts.js', join(tmp, 'blogs.mjs'));
const { conditions } = await import(join(tmp, 'cond.mjs'));
const { defaultBlogPosts } = await import(join(tmp, 'blogs.mjs'));

const q = (s) => (s == null ? 'null' : `$q$${String(s).replace(/\$q\$/g, '')}$q$`);
const j = (o) => `$q$${JSON.stringify(o)}$q$::jsonb`;
const slug = (s) => s.toLowerCase().replace(/&/g, ' and ').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const strip = (html) => String(html || '').replace(/<script[\s\S]*?<\/script>/gi, ' ').replace(/<style[\s\S]*?<\/style>/gi, ' ').replace(/<[^>]+>/g, ' ').replace(/&nbsp;/g, ' ').replace(/&amp;/g, '&').replace(/&#?\w+;/g, ' ').replace(/\s+/g, ' ').trim();

const out = [];
out.push('-- Seed data generated by scripts/gen-seed.mjs from content already on the site.');

out.push(`insert into public.admin_allowlist(email, note) values ('recouph@gmail.com', 'Project owner') on conflict do nothing;`);

const settings = [
  ['notification_emails', JSON.stringify(['connect@recoup.health']), false],
  ['hms_booking_url', JSON.stringify(''), true],
  ['hms_booking_mode', JSON.stringify('unpaid'), true],
  ['razorpay_key_id', JSON.stringify(''), true],
  ['cod_enabled', JSON.stringify(true), true],
  ['whatsapp_number', JSON.stringify('919845155449'), true],
  ['shipping_flat_inr', JSON.stringify(0), false],
  ['free_shipping_above_inr', JSON.stringify(0), false],
  ['home_meta', 'null', true],
  ['robots_txt', 'null', true],
];
out.push('insert into public.site_settings(key, value, is_public) values');
out.push(settings.map(([k, v, p]) => `  ('${k}', $q$${v}$q$::jsonb, ${p})`).join(',\n') + '\non conflict (key) do nothing;');

// blog posts (same sample posts the site shows today)
for (const p of defaultBlogPosts) {
  out.push(`insert into public.blog_posts(slug, title, category, excerpt, body_html, image_url, read_time, meta_title, meta_description, published_at)
values (${q(p.id)}, ${q(p.title)}, ${q(p.category)}, ${q(p.excerpt)}, ${q(p.bodyHtml)}, ${q(p.image)}, ${q(p.readTime)}, ${q(p.metaTitle)}, ${q(p.metaDescription)}, ${q(new Date(p.date).toISOString())}::timestamptz)
on conflict (slug) do nothing;`);
}

// testimonials from the home page
const testimonials = [
  ['Dr. Ananya Iyer', 'Classical Dancer, Bangalore', "My dancing career was almost over due to chronic ankle pain. RECOUP's specialized biomechanical analysis and therapy brought me back to the stage stronger than I was before. I couldn't be more grateful.", '/testimonials/ananya-iyer.jpg', 1],
  ['Rajesh Kumar', 'IT Professional, Hyderabad', "Years of sitting at a desk gave me severe RSI. The team at RECOUP didn't just treat the pain; they taught me how to work and live without hurting my body again. Truly transformative care.", '/testimonials/rajesh-kumar.jpg', 2],
  ['Sunita Reddy', 'Retired Teacher, Chennai', 'I suffered from arthritis for years. Their pain management program gave me a new lease on life. I can now play with my grandchildren without constant pain. Highly recommended.', '/testimonials/sunita-reddy.jpg', 3],
];
out.push('insert into public.testimonials(name, role, content, image_url, sort_order)\nselect * from (values');
out.push(testimonials.map(t => `  (${q(t[0])}, ${q(t[1])}, ${q(t[2])}, ${q(t[3])}, ${t[4]})`).join(',\n'));
out.push(') as v(name, role, content, image_url, sort_order)\nwhere not exists (select 1 from public.testimonials);');

// the 7 fellowship programs shown on the Academy page
const fellowshipSrc = readFileSync('src/components/academy/FellowshipSection.jsx', 'utf8');
const m = fellowshipSrc.match(/const fellowships = (\[[\s\S]*?\n\]);/);
const fellowships = (0, eval)('(' + m[1] + ')');
fellowships.forEach((f, i) => {
  out.push(`insert into public.courses(slug, title, category, summary, syllabus, sort_order)
values (${q(slug(f.title).slice(0, 80))}, ${q(f.title)}, 'fellowship', ${q(f.level1[0] + '. ' + f.level2[0] + '.')}, ${j([{ title: 'Level 1', items: f.level1 }, { title: 'Level 2', items: f.level2 }])}, ${(i + 1) * 10})
on conflict (slug) do nothing;`);
});

// knowledge base for the symptom assistant: the 34 condition programs + key pages
const knowledge = conditions.map((c) => ({
  title: c.title, category: c.category, url: `/conditions/${c.slug}`,
  tags: [c.fullTitle, c.category].filter(Boolean).join('. '),
  content: [c.desc, strip(c.html)].join(' ').slice(0, 4000),
}));
knowledge.push(
  { title: 'EPHR - Early Personalised Health Report', category: 'Diagnostics', url: '/ephr', tags: 'blood report lab results biomarkers health check', content: 'RECOUP EPHR reads blood and lab reports and explains abnormal parameters in simple language, helping patients understand biomarkers and long-term health risks.' },
  { title: 'Hypermobility and EDS Care', category: 'Rehabilitation', url: '/hypermobility', tags: 'hypermobility ehlers danlos double jointed joint instability', content: 'Specialist care for hypermobility spectrum disorders and Ehlers-Danlos syndrome: joint pain, instability, frequent sprains and dislocations, fatigue, dizziness, digestive issues and easy bruising.' },
  { title: 'Functional Nutrition', category: 'Nutrition', url: '/functional-nutrition', tags: 'diet food gut digestion inflammation weight energy', content: 'Root-cause functional nutrition: personalised nutrition for gut health, inflammation, metabolic health, weight, energy and long-term wellness.' },
);
out.push('insert into public.ai_knowledge(title, category, url, tags, content)\nselect * from (values');
out.push(knowledge.map(k => `  (${q(k.title)}, ${q(k.category)}, ${q(k.url)}, ${q(k.tags)}, ${q(k.content)})`).join(',\n'));
out.push(') as v(title, category, url, tags, content)\nwhere not exists (select 1 from public.ai_knowledge);');

writeFileSync('supabase/migrations/002_seed.sql', out.join('\n') + '\n');
console.log('conditions', conditions.length, 'knowledge rows', knowledge.length, 'courses', fellowships.length);
